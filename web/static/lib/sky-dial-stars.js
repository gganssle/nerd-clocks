function hms(s) {
  const [h, m, sec] = s.split(' ').map(Number);
  return (h + m / 60 + sec / 3600) * 15;
}
function dm(s) {
  const sign = s.startsWith('-') ? -1 : 1;
  const [d, m] = s.replace(/^[+-]/, '').split(' ').map(Number);
  return sign * (d + m / 60);
}

